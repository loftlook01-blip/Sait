const rub = (n: number) => new Intl.NumberFormat('ru-RU').format(n) + ' ₽';
/** Стоимость работ для типовой площади, округлённая вверх до тысяч */
export const flatTotal = (f: Flat, pkgId: string) => {
  const p = PACKAGES.find((x) => x.id === pkgId)!;
  return Math.ceil((f.area * p.price) / 1000) * 1000;
};
/** Подставляет цены в текст */
export const fillPrices = (text: string, f: Flat) =>
  text
    .replaceAll('{area}', String(f.area))
    .replace(/\{rate:(\w+)\}/g, (_, id) => rub(PACKAGES.find((x) => x.id === id)!.price))
    .replace(/\{total:(\w+)\}/g, (_, id) => rub(flatTotal(f, id)));
